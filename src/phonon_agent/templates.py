def _stage_script(source_name: str, expression: str) -> str:
    source = (Path(__file__).parent / source_name).read_text(encoding="utf-8")
    source = source.replace("from .", "from phonon_agent.")
    return (
        "#!/usr/bin/env python3\n"
        "# Generated by phonon-agent init. This is an editable stage implementation.\n"
        "# Execute it through: phonon-agent stage <case> <stage>\n"
        + source
        + "\n\ndef run(context):\n"
        + f"    return {expression}\n"
        + "\n\nif __name__ == '__main__':\n"
        + "    raise SystemExit('Run this stage through phonon-agent stage, not directly.')\n"
    )


def init_case(target: Path, *, profile: str | None = None) -> Path:
    target = target.expanduser().resolve()
    if target.exists() and any(target.iterdir()):
        raise FileExistsError(f"target directory is not empty: {target}")
    (target / "inputs" / "dispatcher").mkdir(parents=True, exist_ok=True)
    scripts = target / "scripts"
    scripts.mkdir(parents=True, exist_ok=True)
    workflow = yaml.safe_load(WORKFLOW.format(name=target.name))
    if profile == "agi":
        for section, values in AGI_PROFILE.items():
            workflow[section].update(values)
    elif profile:
        raise ValueError(f"unknown profile: {profile}")
    (target / "workflow.yaml").write_text(
        yaml.safe_dump(workflow, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    (target / "inputs" / "POSCAR").write_text(POSCAR, encoding="utf-8")
    (target / "inputs" / "INCAR").write_text(INCAR, encoding="utf-8")
    (target / "inputs" / "KPOINTS").write_text(KPOINTS, encoding="utf-8")
    (scripts / "README.md").write_text(SCRIPTS_README, encoding="utf-8")
    for filename, (source_name, expression) in SCRIPT_SOURCES.items():
        path = scripts / filename
        path.write_text(_stage_script(source_name, expression), encoding="utf-8")
        os.chmod(path, 0o755)
    (target / ".gitignore").write_text(
        "runs/\nPOTCAR\nmachine.json\nsubmitted_tasks.json\n__pycache__/\n",
        encoding="utf-8",
    )
    return target
